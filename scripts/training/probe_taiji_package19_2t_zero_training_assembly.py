"""19.2t: zero-training end-to-end assembly of the byte-match route.

The route layer is registered in ``candidate_identity.GRAPH_MODULES`` and becomes
the selection readout: the object description and the place description are
matched byte-by-byte against all eight record lines (same identity parameters),
the argmax line is the route and the window start is where the name is read from.
Only the *start* of the copy operator is replaced; transport, span pointer and
``score_rows`` keep their frozen weights.  A single assembled state is saved and
marked ``assembled_zero_training``; no candidate bundle is written otherwise.

Readings are dev-only (192 examples, confirm is never opened), split old/new.  The
main reading uses ``gamma_override = 0`` (pure copy at content positions, null
route only for the fixed template); the secondary reading uses
``gamma_override = gamma_floor`` as a leak control for generated bytes.

Run: ``python scripts/training/probe_taiji_package19_2t_zero_training_assembly.py``
"""

