"""A-task adapter for the Plan C weight-tied baseline (frozen prereg, D-20261119-03).

Wraps `WeightTiedTransformerBaseline(28, 3)` behind the first-A task interface
(`initial/set_goal/action/observe/set_request/output/accept_byte`) so the same
`evaluate()` instrument decodes it.  Everything follows the prereg in
`plans/manifests/taiji_u2_22_5_0_a_parent_package_20261119.json#adapter_prereg`:
per-step 32-dim tokens fused from the three modality encoders with clamp-repeat
padding, request/generated bytes in the text slot, the 8-row position table
re-used with clamp, teacher-forced CE in a single forward+backward per example.
"""

from __future__ import annotations

import sys
from pathlib import Path

import torch
from torch.nn import functional as functional

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from scripts.training.baseline_identity_c_20261117 import (  # noqa: E402
    WeightTiedTransformerBaseline,
)

PREV_START = 255
TOKEN_DIM = 32
MODALITIES = ("rgb", "audio", "proprio")


class ATaskBaselineAdapter(torch.nn.Module):
    """Task-facing wrapper; the frozen identity graph is used untouched."""

    architecture_id = "weight_tied_transformer_sequence+first_a_adapter_v1"

    def __init__(self, seed: int) -> None:
        super().__init__()
        torch.manual_seed(seed)
        self.core = WeightTiedTransformerBaseline(28, 3)
        self.frontend = self.core.frontend

    # -- token construction (prereg: same math as SharedFrontend.step_tokens) --

    def _obs_tokens(self, observations, goal_context: torch.Tensor) -> torch.Tensor:
        dtype = self.frontend.metadata.weight.dtype
        lengths = {name: observations[name].shape[0] for name in MODALITIES}
        steps = lengths["rgb"]
        rows = []
        for step in range(steps):
            coordinate = torch.zeros(8, dtype=dtype)
            coordinate[0] = step / (steps - 1)
            coordinate[6] = 1
            parts = []
            for index, name in enumerate(MODALITIES):
                clamped = min(step, lengths[name] - 1)
                value = observations[name][clamped]
                parts.append(
                    self.frontend.encoder[name](value)
                    + self.frontend.metadata(coordinate)
                    + self.frontend.modality[index]
                )
            rows.append(torch.cat([*parts, self.frontend.metadata(coordinate) + goal_context], -1))
        return torch.stack(rows, 0)

    def _text_token(self, byte: int) -> torch.Tensor:
        token = torch.zeros(TOKEN_DIM, dtype=self.frontend.metadata.weight.dtype)
        token[24:] = self.frontend.text_input(
            self.frontend.embedding(torch.tensor([byte], dtype=torch.long))
        )[0]
        return token

    # -- graph (prereg: frozen identity blocks, position rows clamped to 7) --

    def _hidden(self, sequence: torch.Tensor) -> torch.Tensor:
        core = self.core
        steps = len(sequence)
        rows = torch.clamp(torch.arange(steps), max=core.position.shape[0] - 1)
        hidden = (core.record_in(sequence[None]) + core.position[rows][None])[0]
        mask = torch.triu(torch.ones(steps, steps, dtype=torch.bool), diagonal=1)
        for _ in range(core.applications):
            attended, _ = core.attention(hidden, hidden, hidden, attn_mask=mask, need_weights=False)
            hidden = core.norm_attention(hidden + attended)
            hidden = core.norm_feedforward(hidden + core.feedforward(hidden))
        return hidden

    def _logits(self, hidden: torch.Tensor, position: int, last_byte: int) -> torch.Tensor:
        previous = self.frontend.embedding(torch.tensor([last_byte], dtype=torch.long))[0]
        return self.core.byte_head(torch.cat([hidden[position], previous], -1))

    # -- task interface (first_a_support.prepare/output/accept) --

    def initial(self) -> dict:
        return {}

    def set_goal(self, state: dict, goal: bytes) -> dict:
        state = dict(state)
        state["goal_context"] = self.frontend.text_units(goal.decode("utf-8"))
        return state

    def action(self, state: dict, action: torch.Tensor) -> dict:
        return state  # first-A actions are constant zeros; no encoder in the identity

    def observe(self, state: dict, observations, coordinates, outcome) -> dict:
        state = dict(state)
        state["obs"] = self._obs_tokens(observations, state["goal_context"])
        return state

    def set_request(self, state: dict, request: bytes) -> dict:
        state = dict(state)
        prefix = [row for row in state["obs"]]
        prefix.extend(self._text_token(byte) for byte in request)
        state["prefix"] = torch.stack(prefix, 0)
        state["generated"] = []
        state["last_byte"] = PREV_START
        return state

    def output(self, state: dict) -> torch.Tensor:
        parts = [state["prefix"]]
        if state["generated"]:
            parts.append(torch.stack(state["generated"], 0))
        sequence = torch.cat(parts, 0)
        hidden = self._hidden(sequence)
        logits = self._logits(hidden, len(sequence) - 1, state["last_byte"])
        return functional.softmax(logits, -1)

    def accept_byte(self, state: dict, symbol: int) -> dict:
        state = dict(state)
        state["generated"] = [*state["generated"], self._text_token(symbol)]
        state["last_byte"] = symbol
        return state

    # -- teacher-forced training (prereg: one forward+backward per example) --

    def task_loss(self, public: dict, target: bytes) -> torch.Tensor:
        state = self.set_request(
            self.observe(
                self.set_goal(self.initial(), public["goal"]),
                public["observations"],
                None,
                None,
            ),
            public["request"],
        )
        symbols = [*target, 256]
        prefix_len = state["prefix"].shape[0]
        tokens = [self._text_token(byte) for byte in symbols[:-1]]
        sequence = torch.cat([state["prefix"], torch.stack(tokens, 0)], 0)
        hidden = self._hidden(sequence)
        terms = []
        for index, symbol in enumerate(symbols):
            position = prefix_len + index - 1
            previous = PREV_START if index == 0 else symbols[index - 1]
            logits = self._logits(hidden, position, previous)
            terms.append(functional.cross_entropy(logits[None], torch.tensor([symbol])))
        return torch.stack(terms).mean()
