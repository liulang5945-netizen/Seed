"""20.1 graph identity and registries.

The frozen 19.x identity in :mod:`taiji.candidate_identity` is deliberately left
untouched: extending its ``GRAPH_MODULES`` would change every stored 17/19
``candidate_sha_v2``.  Package 20 therefore registers its own lists here.  The
digest covers the graph contract and the declared parameter shapes, not the
source bytes.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]

GRAPH_MODULES_20 = (
    "taiji/rule_learning_20_1_net.py",
    "taiji/living_core.py",
    "taiji/record_relation_core.py",
)

_LEFT = "应送左箱。".encode()
_RIGHT = "应送右箱。".encode()
DECISION_POSITIONS_20 = tuple(
    position for position in range(len(_LEFT)) if _LEFT[position] != _RIGHT[position]
)

DECODE_RULES_20 = {
    "answer_space": ["应送左箱。", "应送右箱。"],
    "answer_bytes": len(_LEFT),
    "decision_positions": list(DECISION_POSITIONS_20),
    "decode": "greedy argmax over the 256 byte ids on the fixed 15-byte contract",
    "feedback_release": "atomic five-line batches; only released lines enter E and F",
    "fast_write": "CF1 writes F from released feedback only; B_EH never writes F",
    "fast_window": "F edits happen inside the release call; query and self-generated bytes cannot write",
    "session_freeze": "every parameter frozen inside a session; F state is the only inference-plastic tensor",
    "truth_isolation": "rule id, signature, truth table and solver are scoring-only",
    "answer_contract": "应送(左|右)箱。; decision bytes at positions 7..8",
    "store_write": (
        "addressed_store_enabled only: value = the turn's post-read F copy, written at "
        "every turn and at every released line; default off"
    ),
    "store_read": (
        "cosine similarity between the 128-d mean of BytePatchEncoder.context(query) "
        "and the stored keys; softmax temperature 0.1; F <- (1-a)F + a*sum p_i V_i, a=0.5"
    ),
    "addressed_write": "addressed store writes are structural, never gradient driven",
    "fifo": "32 slots, eviction of the lowest insertion age when full",
    "cross_session_clear": (
        "the store is zeroed at the first turn of a new session and is never restored "
        "across a session boundary"
    ),
}

TASK_CONTRACT = {
    "attributes": [
        ["表面", "细", "粗"],
        ["材质", "软", "硬"],
        ["光泽", "哑", "亮"],
        ["结构", "空", "实"],
    ],
    "rule_family": "y = b xor xor_{i in S} x_i, 1<=|S|<=2, |rules|=20",
    "anchors": "0000 and the four basis vectors",
    "sessions": [10, 24, 17],
    "turns": 51,
    "correction_surface": 22,
}

INIT_SCHEME = "parent bundle weights copied verbatim; no new tensor initialised"
STATE_SCHEMA = "taiji-rule-learning-20-1-state-v1"


def sha256_file(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def source_files() -> dict[str, str]:
    return {name: sha256_file(ROOT / name) for name in GRAPH_MODULES_20}


def _digest(payload: dict[str, Any]) -> str:
    return hashlib.sha256(
        json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode(
            "utf-8"
        )
    ).hexdigest()


def graph_identity(graph: Any) -> dict[str, Any]:
    payload = {
        "graph": "taiji-rule-learning-20-1",
        "arm": graph.arm,
        "fast_enabled": bool(graph.fast_enabled),
        "addressed_store_enabled": bool(graph.store_enabled),
        "contract_version": "rule-learning-20-r1",
        "state_schema": STATE_SCHEMA,
        "init_scheme": INIT_SCHEME,
        "modules": list(GRAPH_MODULES_20),
        "decode_rules": DECODE_RULES_20,
        "task_contract": TASK_CONTRACT,
        "parameters": [
            [row["name"], row["shape"], row["dtype"]] for row in graph.parameter_table()
        ],
        "declared_trainable": [
            row["name"] for row in graph.parameter_table() if row["outer_trainable"]
        ],
        "frozen_unused": [
            row["name"] for row in graph.parameter_table() if not row["outer_trainable"]
        ],
    }
    sha = _digest(payload)
    sources = source_files()
    return {
        "candidate_sha_v2": sha,
        "arm": graph.arm,
        "fast_enabled": bool(graph.fast_enabled),
        "addressed_store_enabled": bool(graph.store_enabled),
        "graph": "taiji-rule-learning-20-1",
        "modules": list(GRAPH_MODULES_20),
        "decode_rules": DECODE_RULES_20,
        "task_contract": TASK_CONTRACT,
        "init_scheme": INIT_SCHEME,
        "state_schema": STATE_SCHEMA,
        "parameter_count": sum(row["elements"] for row in graph.parameter_table()),
        "parameter_tensors": len(graph.parameter_table()),
        "group_counts": graph.group_counts(),
        "source_files": sources,
    }
