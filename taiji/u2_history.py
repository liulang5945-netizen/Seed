"""Raw causal history and atomic persistence for the U2 subject.

History entries are immutable snapshots. A finite gradient window references a
prefix while the raw chain survives window truncation and structural boundaries.
"""

from __future__ import annotations

import copy
import hashlib
import io
import os
import struct
import uuid
from collections.abc import Mapping
from dataclasses import fields, is_dataclass
from pathlib import Path
from typing import Any, cast

import torch

MAGIC = b"TAIJI-U2-RECOVERY-1\x00"
HISTORY_SCHEMA = "taiji-u2-raw-history-v2"
MAX_HISTORY_ENTRIES = 96
MAX_HISTORY_BYTES = 16 * 1024 * 1024


def detached_tree(value: Any) -> Any:
    if isinstance(value, torch.Tensor):
        return value.detach().clone()
    if is_dataclass(value) and not isinstance(value, type):
        return type(value)(
            **{field.name: detached_tree(getattr(value, field.name)) for field in fields(value)}
        )
    if isinstance(value, dict):
        return {key: detached_tree(item) for key, item in value.items()}
    if isinstance(value, list):
        return [detached_tree(item) for item in value]
    if isinstance(value, tuple):
        return tuple(detached_tree(item) for item in value)
    return copy.deepcopy(value)


def assert_values_equal(left: Any, right: Any, path: str = "state") -> None:
    """Compare supported values exactly, including signed infinities in log state."""
    if isinstance(left, torch.Tensor):
        if (
            not isinstance(right, torch.Tensor)
            or left.dtype != right.dtype
            or left.shape != right.shape
            or not torch.equal(left.detach().cpu(), right.detach().cpu())
        ):
            raise ValueError(f"Recovery value mismatch at {path}")
    elif is_dataclass(left) and not isinstance(left, type):
        if type(left) is not type(right):
            raise ValueError(f"Recovery type mismatch at {path}")
        for field in fields(left):
            assert_values_equal(
                getattr(left, field.name), getattr(right, field.name), f"{path}.{field.name}"
            )
    elif isinstance(left, Mapping):
        if not isinstance(right, Mapping) or set(left) != set(right):
            raise ValueError(f"Recovery field mismatch at {path}")
        for key, value in left.items():
            assert_values_equal(value, right[key], f"{path}.{key}")
    elif isinstance(left, (list, tuple)):
        if type(left) is not type(right) or len(left) != len(right):
            raise ValueError(f"Recovery sequence mismatch at {path}")
        for index, (a, b) in enumerate(zip(left, right, strict=True)):
            assert_values_equal(a, b, f"{path}[{index}]")
    elif left != right:
        raise ValueError(f"Recovery value mismatch at {path}")


def _hash_value(hasher: Any, value: Any) -> None:
    if isinstance(value, torch.Tensor):
        tensor = value.detach().cpu().contiguous()
        hasher.update(b"tensor" + str(tensor.dtype).encode() + repr(tuple(tensor.shape)).encode())
        hasher.update(tensor.numpy().tobytes())
    elif is_dataclass(value) and not isinstance(value, type):
        hasher.update(type(value).__qualname__.encode())
        for field in fields(value):
            hasher.update(field.name.encode())
            _hash_value(hasher, getattr(value, field.name))
    elif isinstance(value, Mapping):
        hasher.update(b"mapping")
        for key in sorted(value):
            _hash_value(hasher, key)
            _hash_value(hasher, value[key])
    elif isinstance(value, (tuple, list)):
        hasher.update(type(value).__name__.encode() + str(len(value)).encode())
        for item in value:
            _hash_value(hasher, item)
    else:
        hasher.update(type(value).__name__.encode() + repr(value).encode("utf-8"))


def value_digest(value: Any) -> str:
    hasher = hashlib.sha256()
    _hash_value(hasher, value)
    return hasher.hexdigest()


def atomic_save(payload: Any, destination: str | Path) -> Path:
    """Write a trusted local payload with length/SHA framing and atomic replace."""
    path = Path(destination)
    path.parent.mkdir(parents=True, exist_ok=True)
    buffer = io.BytesIO()
    torch.save(payload, buffer)
    data = buffer.getvalue()
    temporary = path.with_name(f".{path.name}.{uuid.uuid4().hex}.writing")
    try:
        with temporary.open("xb") as stream:
            stream.write(MAGIC)
            stream.write(struct.pack(">Q", len(data)))
            stream.write(hashlib.sha256(data).digest())
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)
    return path


def atomic_load(source: str | Path) -> Any:
    """Verify framing before unpickling an artifact generated by this application."""
    raw = Path(source).read_bytes()
    prefix = len(MAGIC) + 8 + 32
    if len(raw) < prefix or raw[: len(MAGIC)] != MAGIC:
        raise ValueError("Invalid recovery file header")
    size = struct.unpack(">Q", raw[len(MAGIC) : len(MAGIC) + 8])[0]
    data = raw[prefix:]
    if len(data) != size or hashlib.sha256(data).digest() != raw[len(MAGIC) + 8 : prefix]:
        raise ValueError("Recovery file length or checksum mismatch")
    return torch.load(io.BytesIO(data), map_location="cpu", weights_only=False)


def _serialized_size(value: Any) -> int:
    buffer = io.BytesIO()
    torch.save(value, buffer)
    return buffer.tell()


class CausalHistory:
    """Persistent-value chain with bounded storage and verified prefix references."""

    def __init__(
        self,
        root: dict[str, Any],
        *,
        max_entries: int = MAX_HISTORY_ENTRIES,
        max_bytes: int = MAX_HISTORY_BYTES,
    ):
        if (
            type(max_entries) is not int
            or not 1 <= max_entries <= MAX_HISTORY_ENTRIES
            or type(max_bytes) is not int
            or not 1 <= max_bytes <= MAX_HISTORY_BYTES
        ):
            raise ValueError("Invalid raw history budget")
        if set(root) != {
            "kind",
            "subject_id",
            "config",
            "parameter_revision",
            "parameter_digest",
            "source_pins",
            "anchor_state",
        } or root["kind"] not in {"genesis", "values"}:
            raise ValueError("Invalid raw history root")
        if (root["kind"] == "genesis") != (root["anchor_state"] is None):
            raise ValueError("Raw history root has inconsistent provenance")
        if type(root["parameter_revision"]) is not int or root["parameter_revision"] < 0:
            raise ValueError("Invalid raw history root revision")
        self._root = detached_tree(root)
        self._entries: tuple[dict[str, Any], ...] = ()
        self.max_entries, self.max_bytes = max_entries, max_bytes
        self._bytes = _serialized_size(self._root)
        self._head = value_digest(self._root)
        if self._bytes > self.max_bytes:
            raise ValueError("raw_history_budget_stop")

    @property
    def entry_count(self) -> int:
        return len(self._entries)

    @property
    def total_bytes(self) -> int:
        return self._bytes

    @property
    def complete(self) -> bool:
        return cast(bool, self._root["kind"] == "genesis")

    @property
    def root(self) -> dict[str, Any]:
        return cast(dict[str, Any], detached_tree(self._root))

    def require_complete(self) -> None:
        if not self.complete:
            raise ValueError("coverage_incomplete: raw history starts at a values anchor")

    def reference(self) -> dict[str, Any]:
        return {"entries": self.entry_count, "head": self._head}

    def validate_reference(self, reference: Mapping[str, Any]) -> int:
        if set(reference) != {"entries", "head"}:
            raise ValueError("Invalid raw history prefix reference")
        count = reference["entries"]
        if type(count) is not int or not 0 <= count <= self.entry_count:
            raise ValueError("Missing raw history prefix")
        head = value_digest(self._root) if count == 0 else self._entries[count - 1]["head"]
        if reference["head"] != head:
            raise ValueError("Raw history prefix identity mismatch")
        return count

    def append(self, payload: dict[str, Any]) -> CausalHistory:
        if set(payload) != {"operation", "parameter_revision", "parameter_digest", "segment"}:
            raise ValueError("Unregistered raw history payload fields")
        operation = payload["operation"]
        if set(operation) != {"kind", "arguments", "expected"}:
            raise ValueError("Unregistered raw operation fields")
        kinds = {
            "goal",
            "records",
            "choose",
            "issue",
            "ack",
            "process_time",
            "receive",
            "begin_utterance",
            "emit",
            "internal",
            "window",
            "birth",
            "update",
        }
        if operation["kind"] not in kinds:
            raise ValueError("Unsupported raw operation")
        segment = payload["segment"]
        previous = self._entries[-1]["payload"]["segment"] if self._entries else 0
        if (
            type(segment) is not int
            or segment < 0
            or segment
            != (previous + 1 if operation["kind"] in {"window", "birth", "update"} else previous)
        ):
            raise ValueError("Invalid raw history segment")
        if type(payload["parameter_revision"]) is not int or payload["parameter_revision"] < 0:
            raise ValueError("Invalid raw history parameter revision")
        previous_revision = (
            self._entries[-1]["payload"]["parameter_revision"]
            if self._entries
            else self._root["parameter_revision"]
        )
        if payload["parameter_revision"] < previous_revision:
            raise ValueError("Raw history parameter revision regressed")
        copied = detached_tree(payload)
        size = _serialized_size(copied)
        if self.entry_count >= self.max_entries or self._bytes + size > self.max_bytes:
            raise ValueError("raw_history_budget_stop")
        node = {
            "sequence": self.entry_count,
            "parent": self._head,
            "payload": copied,
            "payload_bytes": size,
            "payload_digest": value_digest(copied),
        }
        node["head"] = value_digest({key: value for key, value in node.items() if key != "payload"})
        result = object.__new__(CausalHistory)
        result._root = self._root
        result._entries = (*self._entries, node)
        result.max_entries, result.max_bytes = self.max_entries, self.max_bytes
        result._bytes, result._head = self._bytes + size, node["head"]
        return result

    def operations_since(self, reference: Mapping[str, Any]) -> list[dict[str, Any]]:
        count = self.validate_reference(reference)
        operations: list[dict[str, Any]] = []
        for node in self._entries[count:]:
            operation = detached_tree(node["payload"]["operation"])
            if operation["kind"] in {"window", "birth", "update"}:
                raise ValueError("Learning window crosses an unregistered boundary")
            if operations and operation["kind"] == operations[-1]["kind"] == "emit":
                operations[-1]["arguments"]["symbols"].extend(operation["arguments"]["symbols"])
            else:
                operations.append(operation)
        return operations

    def export(self) -> dict[str, Any]:
        return cast(
            dict[str, Any],
            detached_tree(
                {
                    "schema": HISTORY_SCHEMA,
                    "root": self._root,
                    "entries": self._entries,
                    "max_entries": self.max_entries,
                    "max_bytes": self.max_bytes,
                    "head": self._head,
                    "total_bytes": self._bytes,
                }
            ),
        )

    @classmethod
    def restore(cls, payload: dict[str, Any]) -> CausalHistory:
        if (
            set(payload)
            != {
                "schema",
                "root",
                "entries",
                "max_entries",
                "max_bytes",
                "head",
                "total_bytes",
            }
            or payload["schema"] != HISTORY_SCHEMA
        ):
            raise ValueError("Unsupported raw history schema")
        result = cls(
            payload["root"], max_entries=payload["max_entries"], max_bytes=payload["max_bytes"]
        )
        for node in payload["entries"]:
            expected = result.append(node["payload"])
            assert_values_equal(node, expected._entries[-1], "raw_history.node")
            result = expected
        if result._head != payload["head"] or result._bytes != payload["total_bytes"]:
            raise ValueError("Raw history tail identity mismatch")
        return result
